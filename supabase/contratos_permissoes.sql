-- Cria a tabela só se ainda não existir (no seu banco ela já existe)
create table if not exists public.contratos (
  id          bigint generated by default as identity primary key,
  titulo      text,
  dados       jsonb not null default '{}'::jsonb,
  criado_por  text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- Mesmas regras das outras tabelas do sistema (orçamentos, obras…):
-- o sistema grava com a chave pública, então anon precisa ler e gravar.
alter table public.contratos enable row level security;
do $$
declare p record;
begin
  for p in select policyname from pg_policies where schemaname = 'public' and tablename = 'contratos' loop
    execute format('drop policy if exists %I on public.contratos', p.policyname);
  end loop;
end $$;
create policy "contratos acesso sistema" on public.contratos
  for all to anon, authenticated using (true) with check (true);
grant select, insert, update, delete on public.contratos to anon, authenticated;
do $$ begin
  if exists (select 1 from pg_class where relkind = 'S' and relname = 'contratos_id_seq') then
    execute 'grant usage, select on sequence public.contratos_id_seq to anon, authenticated';
  end if;
end $$;

notify pgrst, 'reload schema';

